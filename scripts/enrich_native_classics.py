def main():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    geo_path = os.path.join(root, "public", "data", "geo-books.json")
    with open(geo_path, "r", encoding="utf-8") as f:
        countries = json.load(f)

    updated_count = 0
    for i, c in enumerate(countries):
        cid = str(c.get("id"))
        if cid in NATIVE_ENRICHMENTS:
            countries[i] = NATIVE_ENRICHMENTS[cid]
            updated_count += 1
            
    with open(geo_path, "w", encoding="utf-8") as f:
        json.dump(countries, f, indent=2, ensure_ascii=False)

    print(f"Updated {updated_count} countries with deep native canonical libraries!")
    print(f"Total countries: {len(countries)}, total books: {sum(len(c['books']) for c in countries)}")

if __name__ == "__main__":
    main()
